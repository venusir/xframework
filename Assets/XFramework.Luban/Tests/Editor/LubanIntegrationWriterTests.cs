using System;
using System.Collections.Generic;
using System.IO;
using NUnit.Framework;

namespace XFramework.XConfig.Luban.Editor.Tests
{
    /// <summary>
    /// 接入代码写盘、幂等、stale 清理与覆盖保护用例。
    /// </summary>
    [TestFixture]
    public sealed class LubanIntegrationWriterTests
    {
        private string _dir;

        [SetUp]
        public void SetUp()
        {
            _dir = Path.Combine(
                Path.GetTempPath(), "xfw-luban-integration-" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(_dir);
        }

        [TearDown]
        public void TearDown()
        {
            if (Directory.Exists(_dir))
            {
                Directory.Delete(_dir, true);
            }
        }

        [Test]
        public void Write_CreatesFilesAndManifest()
        {
            var files = new Dictionary<string, string>
            {
                ["RowInterfaces/A.g.cs"] = LubanIntegrationEmitter.AutoGeneratedHeader + "\nA\n",
                ["Adapter/Adp.g.cs"] = LubanIntegrationEmitter.AutoGeneratedHeader + "\nB\n",
            };

            var result = LubanIntegrationWriter.Write(_dir, files, new[] { "tb_a|Map|Row|int" });

            Assert.That(result.Written.Count, Is.EqualTo(2));
            Assert.That(File.Exists(Path.Combine(_dir, "RowInterfaces", "A.g.cs")), Is.True);
            Assert.That(File.Exists(Path.Combine(_dir, "Adapter", "Adp.g.cs")), Is.True);
            Assert.That(File.Exists(Path.Combine(_dir, LubanIntegrationWriter.ManifestFileName)), Is.True);

            var manifest = LubanIntegrationWriter.ReadManifest(_dir);
            Assert.That(manifest.Files.Count, Is.EqualTo(2));
            Assert.That(manifest.Tables, Does.Contain("tb_a|Map|Row|int"));
        }

        [Test]
        public void Write_SecondTime_Unchanged()
        {
            var files = new Dictionary<string, string>
            {
                ["RowInterfaces/A.g.cs"] = LubanIntegrationEmitter.AutoGeneratedHeader + "\nA\n",
            };

            LubanIntegrationWriter.Write(_dir, files, Array.Empty<string>());
            var result = LubanIntegrationWriter.Write(_dir, files, Array.Empty<string>());

            Assert.That(result.Unchanged.Count, Is.EqualTo(1));
            Assert.That(result.Written.Count, Is.EqualTo(0));
        }

        [Test]
        public void Write_RemovesStaleGeneratedFiles()
        {
            var first = new Dictionary<string, string>
            {
                ["RowInterfaces/A.g.cs"] = LubanIntegrationEmitter.AutoGeneratedHeader + "\nA\n",
                ["RowInterfaces/B.g.cs"] = LubanIntegrationEmitter.AutoGeneratedHeader + "\nB\n",
            };

            LubanIntegrationWriter.Write(_dir, first, Array.Empty<string>());

            var second = new Dictionary<string, string>
            {
                ["RowInterfaces/A.g.cs"] = LubanIntegrationEmitter.AutoGeneratedHeader + "\nA\n",
            };

            var result = LubanIntegrationWriter.Write(_dir, second, Array.Empty<string>());

            Assert.That(result.Deleted, Does.Contain("RowInterfaces/B.g.cs"));
            Assert.That(File.Exists(Path.Combine(_dir, "RowInterfaces", "B.g.cs")), Is.False);
        }

        [Test]
        public void Write_RefusesToOverwriteUserFile()
        {
            string path = Path.Combine(_dir, "RowInterfaces", "User.g.cs");
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, "user content");

            var files = new Dictionary<string, string>
            {
                ["RowInterfaces/User.g.cs"] = LubanIntegrationEmitter.AutoGeneratedHeader + "\nX\n",
            };

            Assert.Throws<LubanGenerationException>(
                () => LubanIntegrationWriter.Write(_dir, files, Array.Empty<string>()));
        }

        [Test]
        public void Write_SecondFileRejected_FirstFileUntouched()
        {
            string userPath = Path.Combine(_dir, "RowInterfaces", "ZUser.g.cs");
            Directory.CreateDirectory(Path.GetDirectoryName(userPath));
            File.WriteAllText(userPath, "user content");

            var files = new SortedDictionary<string, string>(StringComparer.Ordinal)
            {
                ["RowInterfaces/A.g.cs"] = LubanIntegrationEmitter.AutoGeneratedHeader + "\nA\n",
                ["RowInterfaces/ZUser.g.cs"] = LubanIntegrationEmitter.AutoGeneratedHeader + "\nX\n",
            };

            Assert.Throws<LubanGenerationException>(
                () => LubanIntegrationWriter.Write(_dir, files, Array.Empty<string>()));
            Assert.That(File.Exists(Path.Combine(_dir, "RowInterfaces", "A.g.cs")), Is.False);
        }

        [Test]
        public void Write_NormalizedDuplicateKeys_Throws()
        {
            var files = new Dictionary<string, string>
            {
                ["RowInterfaces/A.g.cs"] = LubanIntegrationEmitter.AutoGeneratedHeader + "\nA\n",
                ["./RowInterfaces/A.g.cs"] = LubanIntegrationEmitter.AutoGeneratedHeader + "\nB\n",
            };

            Assert.Throws<LubanGenerationException>(
                () => LubanIntegrationWriter.Write(_dir, files, Array.Empty<string>()));
        }

        [Test]
        public void ReadManifest_Malformed_Throws()
        {
            File.WriteAllText(
                Path.Combine(_dir, LubanIntegrationWriter.ManifestFileName),
                "bad header\n");

            Assert.Throws<LubanGenerationException>(
                () => LubanIntegrationWriter.ReadManifest(_dir));
        }
    }
}
